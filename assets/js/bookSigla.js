/**
 * Get sigla for a book ID in the specified locale
 * @param {string} bookId - The book identifier (e.g., "gen", "mat")
 * @param {string} [locale="pl"] - The locale code (e.g., "pl", "en", "de")
 * @returns {string} - The localized sigla or the bookId uppercased if not found
 */
export const getSigla = (bookId, locale = "pl") => {
    const localeSigla = siglaByLocale[locale] || siglaByLocale["en"];
    return localeSigla[bookId] || bookId.toUpperCase();
};

/**
 * Check if we should use sigla (on mobile devices)
 * @returns {boolean}
 */
export const usesMobileSigla = () => {
    return window.innerWidth < 768;
};

export default siglaByLocale;
